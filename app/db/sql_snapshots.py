"""Generate and restore SQL snapshots for application data tables."""
from datetime import datetime
import os
from pathlib import Path
import tempfile

from sqlalchemy import inspect, text

from app.db.engine import PROJECT_ROOT, engine, resolve_database_path, resolve_database_url


TABLE_COLUMNS = {
    "url_masters": ("id", "name", "url", "enabled"),
    "common_venues": ("id", "code", "venue"),
    "prefucture_mst": ("code", "prefucture"),
    "show_info": (
        "id", "showdate", "prefucture", "showname", "venues", "starttime",
        "memo", "url", "favorite", "new",
    ),
    "app_state": ("key", "value"),
}
SNAPSHOT_FILES = {
    "url_masters": "url_masters.sql",
    "common_venues": "common_venues.sql",
    "prefucture_mst": "common_venues.sql",
    "show_info": "show_info.sql",
    "app_state": "crawl_data.sql",
}


def _snapshot_dir() -> Path:
    configured_directory = os.getenv("SQL_SNAPSHOT_DIR")
    if configured_directory:
        return Path(configured_directory)
    if resolve_database_url().get_backend_name() == "sqlite":
        return resolve_database_path().parent / "sql_snapshots"
    return PROJECT_ROOT / "sql_snapshots"


def _quote_identifier(identifier: str) -> str:
    if identifier not in TABLE_COLUMNS and identifier not in {
        column for columns in TABLE_COLUMNS.values() for column in columns
    }:
        raise ValueError(f"Unsupported SQL identifier: {identifier}")
    return f'"{identifier}"'


def _sql_literal(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    value = str(value)
    if "\x00" in value:
        return f"CAST(X'{value.encode('utf-8').hex()}' AS TEXT)"
    return "'" + value.replace("'", "''") + "'"


def _table_sql(table: str, rows) -> str:
    columns = TABLE_COLUMNS[table]
    quoted_columns = ", ".join(_quote_identifier(column) for column in columns)
    statements = [f"-- BEGIN TABLE {table}", f"DELETE FROM {_quote_identifier(table)};"]
    for row in rows:
        values = ", ".join(_sql_literal(row[column]) for column in columns)
        statements.append(
            f"INSERT INTO {_quote_identifier(table)} ({quoted_columns}) VALUES ({values});"
        )
    statements.append(f"-- END TABLE {table}")
    return "\n".join(statements)


def _sql_statements(sql_text: str):
    """Split generated SQL on semicolons outside quoted values and identifiers."""
    statement = []
    in_string = False
    in_identifier = False
    index = 0
    while index < len(sql_text):
        character = sql_text[index]
        statement.append(character)
        if in_string and character == "'":
            if index + 1 < len(sql_text) and sql_text[index + 1] == "'":
                index += 1
                statement.append(sql_text[index])
            else:
                in_string = False
        elif in_identifier and character == '"':
            if index + 1 < len(sql_text) and sql_text[index + 1] == '"':
                index += 1
                statement.append(sql_text[index])
            else:
                in_identifier = False
        elif not in_string and not in_identifier:
            if character == "'":
                in_string = True
            elif character == '"':
                in_identifier = True
            elif character == ";":
                yield "".join(statement).strip()
                statement = []
        index += 1
    if "".join(statement).strip():
        raise ValueError("Incomplete SQL snapshot statement")


def write_table_snapshot(table: str) -> Path:
    tables = ("prefucture_mst", "common_venues") if table == "common_venues" else (table,)
    return _write_snapshot(tables, SNAPSHOT_FILES[table])


def write_crawl_snapshot() -> Path:
    return _write_snapshot(("app_state",), "crawl_data.sql")


def _write_snapshot(tables, filename: str) -> Path:
    sections = [
        "-- Generated by NohCrawler; applying this file replaces the listed tables.",
        f"-- Snapshot time: {datetime.now().astimezone().isoformat(timespec='seconds')}",
        "BEGIN TRANSACTION;",
    ]
    with engine.connect() as conn:
        for table in tables:
            columns = TABLE_COLUMNS[table]
            selected = ", ".join(_quote_identifier(column) for column in columns)
            rows = conn.execute(
                text(f"SELECT {selected} FROM {_quote_identifier(table)} ORDER BY 1")
            ).mappings().all()
            sections.append(_table_sql(table, rows))
    sections.append("COMMIT;")

    directory = _snapshot_dir()
    directory.mkdir(parents=True, exist_ok=True)
    destination = directory / filename
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", newline="\n", dir=directory,
            prefix=f".{filename}.", suffix=".tmp", delete=False,
        ) as temporary:
            temporary_path = Path(temporary.name)
            temporary.write("\n\n".join(sections) + "\n")
        os.replace(temporary_path, destination)
    finally:
        if temporary_path and temporary_path.exists():
            temporary_path.unlink()
    return destination


def restore_empty_tables(conn, tables) -> set[str]:
    """Restore requested tables from their current SQL snapshots if empty."""
    restored = set()
    inspector = inspect(conn)
    for table in tables:
        if table not in TABLE_COLUMNS or not inspector.has_table(table):
            continue
        if conn.execute(text(f"SELECT 1 FROM {_quote_identifier(table)} LIMIT 1")).first():
            continue
        snapshot_paths = [_snapshot_dir() / SNAPSHOT_FILES[table]]
        if table == "show_info":
            snapshot_paths.append(_snapshot_dir() / "crawl_data.sql")
        snapshot_path = next((path for path in snapshot_paths if path.is_file()), None)
        if snapshot_path is None:
            continue
        sql_text = snapshot_path.read_text(encoding="utf-8")
        marker_start = f"-- BEGIN TABLE {table}"
        marker_end = f"-- END TABLE {table}"
        if marker_start not in sql_text or marker_end not in sql_text:
            continue
        block = sql_text.split(marker_start, 1)[1].split(marker_end, 1)[0]
        for statement in _sql_statements(block):
            conn.exec_driver_sql(statement)
        restored.add(table)
    return restored


def ensure_restored(*tables) -> set[str]:
    with engine.begin() as conn:
        return restore_empty_tables(conn, tables)


def initialize_sql_snapshots() -> None:
    tables = ("url_masters", "prefucture_mst", "common_venues", "show_info", "app_state")
    ensure_restored(*tables)
    inspector = inspect(engine)
    for table in ("url_masters", "common_venues", "show_info"):
        if not inspector.has_table(table):
            continue
        write_table_snapshot(table)

    if inspector.has_table("show_info"):
        with engine.begin() as conn:
            conn.execute(text("""
                CREATE TABLE IF NOT EXISTS app_state (
                    key TEXT PRIMARY KEY,
                    value TEXT NOT NULL
                )
            """))
    if inspect(engine).has_table("app_state"):
        # Rewrite older combined snapshots so show_info data is kept only in show_info.sql.
        write_crawl_snapshot()
